#!/usr/bin/env node
// Build the Worker-side media evidence module from the locally generated media-manifest.json.
//
// The emitted module contains NO media bytes and NO credentials. It pins only the exact public
// object identity required for read-only R2 verification: post/figure mapping, R2 key, byte size,
// and SHA-256. The local source path is intentionally omitted.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  MANIFEST_PATH,
  loadManifest,
  verifyManifestIntegrity,
} from './build-media-manifest.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUTPUT_PATH = resolve(ROOT, 'cloudflare/generated/media-manifest.mjs');
const REQUIREMENTS_PATH = resolve(ROOT, 'cloudflare/generated/media-requirements.json');

function requiredIdentity() {
  const parsed = JSON.parse(readFileSync(REQUIREMENTS_PATH, 'utf8'));
  if (!parsed || !Array.isArray(parsed.objects) || parsed.objects.length !== 4) {
    throw new Error('media requirements must contain exactly four objects');
  }

  return parsed.objects.map((object) => ({
    postId: object.postId,
    figure: object.figure,
    logicalMediaId: object.logicalMediaId,
    keyPrefix: object.keyPrefix,
  }));
}

export function sanitizeManifest(manifest) {
  const integrity = verifyManifestIntegrity(manifest);
  if (!integrity.ok) {
    throw new Error(`media manifest integrity failed: ${integrity.reason}`);
  }

  if (!Array.isArray(manifest.objects) || manifest.objects.length !== 4) {
    throw new Error('media manifest must contain exactly four objects');
  }

  const required = requiredIdentity();
  const actual = manifest.objects.map((object) => ({
    postId: object.postId,
    figure: object.figure,
    logicalMediaId: object.logicalMediaId,
    keyPrefix: `media/figures/${object.logicalMediaId}`,
  }));

  if (JSON.stringify(actual) !== JSON.stringify(required)) {
    throw new Error('media manifest does not match the canonical four required figures');
  }

  const objects = manifest.objects.map((object) => ({
    postId: object.postId,
    figure: object.figure,
    logicalMediaId: object.logicalMediaId,
    r2Key: object.r2Key,
    extension: object.extension,
    byteSize: object.byteSize,
    sha256: object.sha256,
  }));

  return {
    format: 1,
    objects,
    manifestSha256: manifest.manifestSha256,
  };
}

export function renderWorkerManifest(manifest) {
  const sanitized = sanitizeManifest(manifest);
  return [
    '// Generated by scripts/build-cloudflare-media-manifest.mjs. DO NOT HAND-EDIT.',
    '// Contains hashes/sizes only; media bytes remain in R2 and local source paths are omitted.',
    '',
    'export const MEDIA_MANIFEST_CONFIGURED = true;',
    '',
    `export const MEDIA_MANIFEST = Object.freeze(${JSON.stringify(sanitized, null, 2)});`,
    '',
  ].join('\n');
}

function main() {
  const manifest = loadManifest(MANIFEST_PATH);
  const source = renderWorkerManifest(manifest);
  writeFileSync(OUTPUT_PATH, source, 'utf8');

  const sanitized = sanitizeManifest(manifest);
  console.log(`Built Worker media evidence: ${sanitized.objects.length} objects`);
  console.log(`Manifest SHA-256: ${sanitized.manifestSha256}`);
  console.log(`Output: ${OUTPUT_PATH}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main();
  } catch (error) {
    console.error(
      `build-cloudflare-media-manifest: ${error instanceof Error ? error.message : String(error)}`,
    );
    process.exitCode = 1;
  }
}
